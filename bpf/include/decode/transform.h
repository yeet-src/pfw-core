/* pfw: table-driven decode steps (the DECODE_HUFFMAN / DECODE_TRANSFORM
 * machines). A nibble machine runs over the reassembled stream emitting decoded
 * bytes into st->dec; the evolving state lives in the map (st->huff_*) and is
 * reloaded each iteration so the verifier launders its precision — the same
 * trick ac_step uses. tf_step reads the baked const table; tf_map_step reads a
 * host-loaded tt_cells table. cp_step copies the decoded output back. */
#ifndef PFW_TRANSFORM_H
#define PFW_TRANSFORM_H

#include "core/common.h"
#include "core/maps.h"
#include "huff_table.h" /* const huff_cells[], generated by src/huffman.js */

/* Run the loaded nibble machine over one input byte (two nibbles, high then
 * low), emitting decoded bytes into the flow's reassembled view. Mirrors
 * huffDecode() in app/lib/pfw/huffman.js. State and output cursor carry in the
 * ctx across the bytes, so a code split across bytes decodes whole. */
/* One input byte (two nibbles) of the nibble machine, reading the const table
 * directly (no helper call in the loop: that forces the verifier to walk every
 * iteration and blows the jump budget) and writing decoded bytes to st->dec.
 * Mirrors huffDecode() in app/lib/pfw/huffman.js. */
struct tf_ctx { struct flow *f; struct pfw_state *st; __u32 n; };
static long __attribute__((unused)) tf_step(__u32 i, void *ctx_)
{
    struct tf_ctx *c = ctx_;
    struct pfw_state *st = c->st;
    if (!st || i >= c->n || st->huff_fail)
        return 1;
    __u8 byte = c->f->reasm[PFW_MASK(i, REASM_CAP)];
    __u32 state = st->huff_state & (TT_STATES - 1); /* reload (laundered) each iter */
    __u32 outpos = st->huff_outpos;
    for (int half = 0; half < 2; half++) {
        __u32 nib = (half == 0 ? (byte >> 4) : byte) & 0xf;
        __u32 cell = huff_cells[PFW_MASK(((state & (TT_STATES - 1)) * 16 + nib), TT_CELLS)];
        if (cell & TT_FAIL) { st->huff_fail = 1; return 1; }
        if (cell & TT_EMIT) {
            if (outpos < REASM_CAP) { /* bounded, else the st->dec write is unbounded */
                st->dec[outpos] = (__u8) (cell >> TT_SYM_SHIFT);
                outpos++;
            }
        }
        state = cell & TT_NEXT;
    }
    st->huff_state = state;
    st->huff_outpos = outpos;
    return 0;
}

/* The general (loadable) decode step: same machine as tf_step, but the table is
 * read per-cell from the tt_cells map instead of a baked const — so any table
 * the host loads works with no kernel change. The map lookup in the loop would
 * trip the verifier's jump budget on its own; it verifies here for exactly the
 * reason ac_step does — the evolving state lives in the map (st->huff_*) and is
 * reloaded each iteration, so its precision is laundered. `base` selects the
 * table: table_id * TT_CELLS. */
struct tf_map_ctx { struct flow *f; struct pfw_state *st; __u32 base, n; };
static long __attribute__((unused)) tf_map_step(__u32 i, void *ctx_)
{
    struct tf_map_ctx *c = ctx_;
    struct pfw_state *st = c->st;
    if (!st || i >= c->n || st->huff_fail)
        return 1;
    __u8 byte = c->f->reasm[PFW_MASK(i, REASM_CAP)];
    __u32 state = st->huff_state & (TT_STATES - 1);
    __u32 outpos = st->huff_outpos;
    for (int half = 0; half < 2; half++) {
        __u32 nib = (half == 0 ? (byte >> 4) : byte) & 0xf;
        __u32 key = c->base + ((state * 16 + nib) & (TT_CELLS - 1));
        __u32 *cp = bpf_map_lookup_elem(&tt_cells, &key);
        __u32 cell = cp ? *cp : TT_FAIL;
        if (cell & TT_FAIL) { st->huff_fail = 1; return 1; }
        if (cell & TT_EMIT) {
            if (outpos < REASM_CAP) {
                st->dec[outpos] = (__u8) (cell >> TT_SYM_SHIFT);
                outpos++;
            }
        }
        state = cell & TT_NEXT;
    }
    st->huff_state = state;
    st->huff_outpos = outpos;
    return 0;
}

/* Copy the decoded output from st->dec into st->view, the buffer the matcher
 * reads after a decode stage. The flow's reassembled stream is left untouched,
 * so the next segment still lands in the stream it belongs to. */
struct cp_ctx { struct flow *f; struct pfw_state *st; __u32 n; };
static long cp_step(__u32 i, void *ctx_)
{
    struct cp_ctx *c = ctx_;
    if (i >= c->n)
        return 1;
    c->st->view[PFW_MASK(i, REASM_CAP)] = c->st->dec[PFW_MASK(i, REASM_CAP)];
    return 0;
}

#endif /* PFW_TRANSFORM_H */
